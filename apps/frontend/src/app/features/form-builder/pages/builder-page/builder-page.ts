import { Component, inject, input, resource } from '@angular/core';
import { SkeletonModule } from 'primeng/skeleton';
import { TranslatePipe } from '@ngx-translate/core';
import { Button } from '@/app/ui/components/button/button';
import { BuilderHeader } from '../../components/builder-header/builder-header';
import { BuilderPropertiesSidebar } from '../../components/builder-properties-sidebar/builder-properties-sidebar';
import { BuilderSidebar } from '../../components/builder-sidebar/builder-sidebar';
import { BuilderWorkspace } from '../../components/builder-workspace/builder-workspace';
import { FormBuilderSync } from '../../services/form-builder-sync';
import { BuilderMenuState } from '../../services/builder-menu-state';
import { BuilderPreviewState } from '../../services/builder-preview-state';

@Component({
  selector: 'app-builder-page',
  imports: [
    BuilderHeader,
    BuilderSidebar,
    BuilderWorkspace,
    BuilderPropertiesSidebar,
    TranslatePipe,
    SkeletonModule,
    Button,
  ],
  providers: [FormBuilderSync],
  templateUrl: './builder-page.html',
})
export class BuilderPage {
  private readonly sync = inject(FormBuilderSync);

  readonly menuState = inject(BuilderMenuState);
  readonly previewState = inject(BuilderPreviewState);

  /** Form id from the route; it is generated by the frontend when the form is created. */
  readonly id = input.required<string>();

  /** Used by the `canDeactivate` guard before the route is left. */
  canLeave(): Promise<boolean> {
    return this.sync.canLeave();
  }

  /** Loads the form, creating it with the route id when it doesn't exist yet. */
  protected readonly form = resource({
    params: () => this.id(),
    loader: ({ params: id }) => this.sync.load(id),
  });
}
